// E-mail reminders for the personal learning calendar.
// Plan times are "floating" local times; the user's time zone (stored with the preferences) turns
// them into real instants. A reminder is sent once per (item, offset), never for reminder moments that
// had already passed when the session was planned, and never after the session started.
import crypto from 'node:crypto';
import { get, all, run } from '../db.js';
import { config } from '../config.js';
import { loadCourseById } from '../catalog.js';
import { sendMail } from './mail.js';

export const OFFSETS = [10, 30, 60, 180, 1440, 2880];

/** Floating local "YYYY-MM-DDTHH:MM" in `tz` → epoch ms. */
export function zonedToEpoch(local, tz) {
  const guess = Date.parse(local + ':00Z');
  let fmt;
  try { fmt = new Intl.DateTimeFormat('en-CA', { timeZone: tz, hourCycle: 'h23', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit' }); } catch { return guess; }
  const asLocal = (t) => { const p = Object.fromEntries(fmt.formatToParts(new Date(t)).map((x) => [x.type, x.value])); return Date.parse(`${p.year}-${p.month}-${p.day}T${p.hour}:${p.minute}:${p.second}Z`); };
  let t = guess - (asLocal(guess) - guess);
  t = guess - (asLocal(t) - t);
  return t;
}

export const unsubToken = (userId) => crypto.createHmac('sha256', config.mediaSigningSecret).update(`unsub:${userId}`).digest('hex').slice(0, 32);

const TXT = {
  en: { in: (m) => (m >= 2880 ? 'in 2 days' : m >= 1440 ? 'tomorrow' : m >= 180 ? `in ${m / 60} hours` : m >= 60 ? 'in 1 hour' : `in ${m} minutes`), subj: (when, t, at) => `${when[0].toUpperCase() + when.slice(1)}: ${t} (${at})`,
    hi: 'Hello', body: (when, t, at, mins) => `You planned a learning session ${when}:`, at: 'Starts', len: 'Planned time', open: 'Open the course', note: 'Your note', unsub: 'Switch off reminder e-mails', demo: 'Demo build: this message was generated by the MedTranslate demo.' },
  de: { in: (m) => (m >= 2880 ? 'in 2 Tagen' : m >= 1440 ? 'morgen' : m >= 180 ? `in ${m / 60} Stunden` : m >= 60 ? 'in 1 Stunde' : `in ${m} Minuten`), subj: (when, t, at) => `${when[0].toUpperCase() + when.slice(1)}: ${t} (${at})`,
    hi: 'Hallo', body: (when) => `du hast eine Lerneinheit geplant – ${when}:`, at: 'Beginn', len: 'Geplante Zeit', open: 'Kurs öffnen', note: 'Deine Notiz', unsub: 'Erinnerungs-E-Mails abschalten', demo: 'Demo-Version: Diese Nachricht wurde von der MedTranslate-Demo erzeugt.' },
};

export function buildReminder({ user, course, item, offset, tz }) {
  const L = TXT[user.preferred_language] || TXT.en;
  const when = L.in(offset);
  const [d, t] = item.start_at.split('T');
  const fmtDate = new Intl.DateTimeFormat(TXT[user.preferred_language] ? user.preferred_language : 'en', { weekday: 'long', day: 'numeric', month: 'long' }).format(new Date(d + 'T12:00:00Z'));
  const at = `${fmtDate}, ${t}`;
  const link = `${config.publicUrl}/courses/${course.slug}`;
  const unsub = `${config.publicUrl}/api/plan/unsubscribe?u=${user.id}&t=${unsubToken(user.id)}`;
  const text = [`${L.hi} ${user.first_name},`, '', L.body(when), '', `  ${course.title}`, `  ${L.at}: ${at} (${tz})`, `  ${L.len}: ${item.minutes} min`, item.note ? `  ${L.note}: ${item.note}` : '', '', `${L.open}: ${link}`, '', '—', L.unsub + ': ' + unsub, L.demo].filter((x) => x !== null).join('\n');
  const e = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  const html = `<div style="font-family:Inter,Arial,sans-serif;max-width:520px;margin:auto;color:#0F172A"><div style="background:#0A1A33;color:#fff;padding:18px 24px;border-radius:14px 14px 0 0;font-weight:700">Med<span style="color:#22D3EE">Translate</span></div>
<div style="border:1px solid #E2E8F0;border-top:0;border-radius:0 0 14px 14px;padding:24px"><p>${e(L.hi)} ${e(user.first_name)},</p><p>${e(L.body(when))}</p>
<h2 style="margin:8px 0;font-size:20px">${e(course.title)}</h2><p style="color:#475569;margin:0">${e(L.at)}: <b>${e(at)}</b> (${e(tz)})<br>${e(L.len)}: ${item.minutes} min${item.note ? `<br>${e(L.note)}: ${e(item.note)}` : ''}</p>
<p><a href="${e(link)}" style="display:inline-block;background:#22D3EE;color:#0A1A33;font-weight:700;padding:12px 20px;border-radius:10px;text-decoration:none">${e(L.open)}</a></p>
<p style="color:#94A3B8;font-size:12px"><a href="${e(unsub)}" style="color:#94A3B8">${e(L.unsub)}</a><br>${e(L.demo)}</p></div></div>`;
  return { subject: L.subj(when, course.title, at), text, html };
}

export function getPrefs(userId) {
  const p = get('SELECT * FROM plan_prefs WHERE user_id = ?', userId);
  let offsets = [1440, 60];
  try { if (p) offsets = JSON.parse(p.offsets).filter((x) => OFFSETS.includes(x)); } catch { /* default */ }
  return { enabled: !!p?.email_on, offsets, tz: p?.tz || 'UTC' };
}

/** Sends every reminder that is due at `now` (ms). Returns the number of messages handled. */
export async function processReminders(now = Date.now()) {
  const rows = all(`SELECT i.*, u.email, u.first_name, u.preferred_language, u.disabled, p.offsets, p.tz FROM plan_items i
    JOIN plan_prefs p ON p.user_id = i.user_id AND p.email_on = 1 JOIN users u ON u.id = i.user_id
    WHERE i.done = 0 AND u.disabled = 0 AND i.start_at >= ?`, new Date(now - 36 * 3600e3).toISOString().slice(0, 16));
  let handled = 0;
  for (const it of rows) {
    const start = zonedToEpoch(it.start_at, it.tz);
    if (now >= start) continue;
    let offsets = []; try { offsets = JSON.parse(it.offsets); } catch { /* none */ }
    const created = Date.parse(it.created_at.replace(' ', 'T') + 'Z');
    const pending = offsets.filter((o) => OFFSETS.includes(o) && now >= start - o * 60000 && !get('SELECT 1 FROM plan_reminders WHERE plan_id = ? AND offset_min = ?', it.id, o)).sort((x, y) => x - y);
    if (!pending.length) continue;
    // Only the most relevant (closest) reminder is sent; earlier ones that are already overdue are skipped.
    const [off, ...older] = pending;
    for (const o of older) run("INSERT INTO plan_reminders (plan_id, offset_min, status) VALUES (?,?, 'skipped')", it.id, o);
    if (created > start - off * 60000) { run("INSERT INTO plan_reminders (plan_id, offset_min, status) VALUES (?,?, 'skipped')", it.id, off); continue; }
    const course = loadCourseById(it.course_id); if (!course) continue;
    const msg = buildReminder({ user: { id: it.user_id, first_name: it.first_name, preferred_language: it.preferred_language }, course, item: it, offset: off, tz: it.tz });
    run("INSERT INTO plan_reminders (plan_id, offset_min, status) VALUES (?,?, 'pending')", it.id, off);
    const r = await sendMail({ userId: it.user_id, to: it.email, ...msg });
    run('UPDATE plan_reminders SET status = ? WHERE plan_id = ? AND offset_min = ?', r.status === 'sent' ? 'sent' : r.status === 'failed' ? 'failed' : 'outbox', it.id, off);
    handled++;
  }
  return handled;
}
